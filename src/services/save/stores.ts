import type { KeyValueStore } from '../../platform/types';

/** In-memory store: the fake for tests and the last resort when no storage is available. */
export class MemoryStore implements KeyValueStore {
  readonly entries = new Map<string, string>();

  async get(key: string): Promise<string | null> {
    return this.entries.get(key) ?? null;
  }

  async set(key: string, value: string): Promise<void> {
    this.entries.set(key, value);
  }

  async remove(key: string): Promise<void> {
    this.entries.delete(key);
  }
}

/** Web adapter. Errors (quota, blocked storage) surface as rejections; SaveService handles them. */
export class WebStorageStore implements KeyValueStore {
  constructor(private readonly storage: Storage) {}

  async get(key: string): Promise<string | null> {
    return this.storage.getItem(key);
  }

  async set(key: string, value: string): Promise<void> {
    this.storage.setItem(key, value);
  }

  async remove(key: string): Promise<void> {
    this.storage.removeItem(key);
  }
}
